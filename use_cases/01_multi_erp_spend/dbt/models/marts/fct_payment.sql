-- AP payment performance: days paid vs due, early-payment discounts taken or lost (2/10 net 30).
WITH fx AS (SELECT CURRENCY, MONTH, USD_PER_UNIT FROM {{ source('src_third_party', 'fx_rates_monthly') }}),
p AS (SELECT * FROM {{ ref('payment') }})
SELECT p.SOURCE_SLOT, p.SOURCE_SYSTEM, p.COMPANY_CODE, p.INVOICE_ID, p.SUPPLIER_ID, x.GOLDEN_SUPPLIER_ID,
       COALESCE(p.PAYMENT_TERMS, x.PAYMENT_TERMS) AS PAYMENT_TERMS,
       p.INVOICE_DATE, p.DUE_DATE, p.PAYMENT_DATE, DATE_TRUNC('month', p.PAYMENT_DATE) AS PAYMENT_MONTH,
       p.AMOUNT * f.USD_PER_UNIT AS AMOUNT_USD, COALESCE(p.DISCOUNT_TAKEN, 0) * f.USD_PER_UNIT AS DISCOUNT_TAKEN_USD,
       DATEDIFF(day, p.INVOICE_DATE, p.PAYMENT_DATE) AS DAYS_TO_PAY,
       DATEDIFF(day, p.DUE_DATE, p.PAYMENT_DATE) AS DAYS_LATE,
       (p.PAYMENT_DATE > p.DUE_DATE) AS IS_LATE,
       (COALESCE(p.PAYMENT_TERMS, x.PAYMENT_TERMS) = '2/10N30') AS DISCOUNT_ELIGIBLE,
       IFF(COALESCE(p.PAYMENT_TERMS, x.PAYMENT_TERMS) = '2/10N30' AND COALESCE(p.DISCOUNT_TAKEN, 0) = 0, p.AMOUNT * 0.02 * f.USD_PER_UNIT, 0) AS DISCOUNT_LOST_USD,
       (p.DISCOUNT_TAKEN IS NULL) AS DISCOUNT_DATA_MISSING
FROM p
LEFT JOIN fx f ON f.CURRENCY = p.CURRENCY AND f.MONTH = DATE_TRUNC('month', p.INVOICE_DATE)
LEFT JOIN {{ ref('int_supplier_xref') }} x ON x.SOURCE_SLOT = p.SOURCE_SLOT AND x.SUPPLIER_ID = p.SUPPLIER_ID
