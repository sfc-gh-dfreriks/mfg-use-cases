-- Same material, same quarter, different plants: how far each plant's average USD price sits above
-- the best plant, against the contract price, and after removing commodity (PPI) movement.
-- Direct materials only: energy and services are priced by local markets and are not comparable.
WITH q AS (
  SELECT MATERIAL, ANY_VALUE(ITEM_TEXT) AS ITEM_TEXT, CATEGORY, PLANT, PLANT_NAME, COMPANY_NAME, SOURCE_SYSTEM, DATE_TRUNC('quarter', PO_DATE) AS QUARTER,
         SUM(SPEND_USD) AS SPEND_USD, SUM(QUANTITY) AS QUANTITY, SUM(SPEND_USD) / NULLIF(SUM(QUANTITY), 0) AS AVG_PRICE_USD,
         COUNT(DISTINCT GOLDEN_SUPPLIER_ID) AS SUPPLIERS, AVG(IFF(IS_ON_CONTRACT, 1, 0)) AS ON_CONTRACT_SHARE, ANY_VALUE(PPI_SERIES) AS PPI_SERIES
  FROM {{ ref('fct_spend') }} WHERE MATERIAL IS NOT NULL AND QUANTITY > 0 AND IS_DIRECT
  GROUP BY MATERIAL, CATEGORY, PLANT, PLANT_NAME, COMPANY_NAME, SOURCE_SYSTEM, QUARTER
),
best AS (SELECT MATERIAL, QUARTER, MIN(AVG_PRICE_USD) AS BEST_PRICE_USD, COUNT(DISTINCT PLANT) AS PLANTS_BUYING FROM q GROUP BY 1, 2),
k AS (SELECT MATERIAL, AVG(CONTRACT_PRICE_USD) AS CONTRACT_PRICE_USD FROM {{ ref('contract_item') }} GROUP BY 1),
ppi AS (SELECT SERIES_ID, DATE_TRUNC('quarter', MONTH) AS QUARTER, AVG(INDEX_VALUE) AS PPI FROM {{ source('src_third_party', 'ppi_index') }} GROUP BY 1, 2),
ppi0 AS (SELECT SERIES_ID, PPI AS PPI_BASE FROM ppi WHERE QUARTER = '2024-01-01')
SELECT q.*, b.BEST_PRICE_USD, b.PLANTS_BUYING, k.CONTRACT_PRICE_USD,
       q.AVG_PRICE_USD / NULLIF(b.BEST_PRICE_USD, 0) - 1 AS PREMIUM_VS_BEST_PCT,
       (q.AVG_PRICE_USD - b.BEST_PRICE_USD) * q.QUANTITY AS SAVINGS_AT_BEST_PRICE_USD,
       q.AVG_PRICE_USD / NULLIF(k.CONTRACT_PRICE_USD, 0) - 1 AS PREMIUM_VS_CONTRACT_PCT,
       p.PPI / NULLIF(p0.PPI_BASE, 0) AS PPI_FACTOR,
       q.AVG_PRICE_USD / NULLIF(p.PPI / NULLIF(p0.PPI_BASE, 0), 0) AS PPI_ADJUSTED_PRICE_USD
FROM q JOIN best b ON b.MATERIAL = q.MATERIAL AND b.QUARTER = q.QUARTER
LEFT JOIN k ON k.MATERIAL = q.MATERIAL
LEFT JOIN ppi p ON p.SERIES_ID = q.PPI_SERIES AND p.QUARTER = q.QUARTER
LEFT JOIN ppi0 p0 ON p0.SERIES_ID = q.PPI_SERIES
