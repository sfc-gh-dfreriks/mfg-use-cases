-- PO-line spend for every selected source, in USD at the PO month's rate, with golden supplier,
-- normalized category, and contract / maverick flags.
WITH fx AS (SELECT CURRENCY, MONTH, USD_PER_UNIT FROM {{ source('src_third_party', 'fx_rates_monthly') }}),
mg AS (SELECT * FROM {{ source('src_third_party', 'ref_material_group') }}),
org AS (SELECT * FROM {{ source('src_third_party', 'ref_org') }})
SELECT
  p.SOURCE_SLOT, p.SOURCE_SYSTEM, p.COMPANY_CODE, o.COMPANY_NAME, p.PLANT, COALESCE(o.PLANT_NAME, p.PLANT) AS PLANT_NAME, o.COUNTRY AS PLANT_COUNTRY,
  p.PO_NUMBER, p.PO_ITEM, p.PO_DATE, DATE_TRUNC('month', p.PO_DATE) AS PO_MONTH, YEAR(p.PO_DATE) AS PO_YEAR, p.DELIVERY_DATE,
  p.SUPPLIER_ID, x.GOLDEN_SUPPLIER_ID, s.SUPPLIER_NAME AS GOLDEN_SUPPLIER_NAME,
  p.MATERIAL, p.ITEM_TEXT,
  COALESCE(mg.MATERIAL_GROUP, cm.MATERIAL_GROUP) AS MATERIAL_GROUP,
  COALESCE(mg.MATERIAL_GROUP_TEXT, cm.MATERIAL_GROUP_TEXT, 'Unclassified') AS CATEGORY,
  IFF(mg.MATERIAL_GROUP IS NOT NULL, 'source code', IFF(cm.MATERIAL_GROUP IS NOT NULL, 'AI_CLASSIFY', 'none')) AS CATEGORY_METHOD,
  COALESCE(mg2.DIRECT, mg.DIRECT) AS IS_DIRECT, COALESCE(mg2.UNSPSC, mg.UNSPSC) AS UNSPSC, COALESCE(mg2.PPI_SERIES, mg.PPI_SERIES) AS PPI_SERIES,
  p.QUANTITY, p.UOM, p.CURRENCY, p.NET_PRICE AS NET_PRICE_LOCAL, p.NET_VALUE AS SPEND_LOCAL,
  p.NET_PRICE * f.USD_PER_UNIT AS NET_PRICE_USD, p.NET_VALUE * f.USD_PER_UNIT AS SPEND_USD,
  p.CONTRACT_ID, (p.CONTRACT_ID IS NOT NULL) AS IS_ON_CONTRACT,
  (p.CONTRACT_ID IS NULL AND COALESCE(mg2.DIRECT, mg.DIRECT, FALSE)) AS IS_MAVERICK
FROM {{ ref('po_line') }} p
LEFT JOIN fx f ON f.CURRENCY = p.CURRENCY AND f.MONTH = DATE_TRUNC('month', p.PO_DATE)
LEFT JOIN mg ON mg.MATERIAL_GROUP = p.MATERIAL_GROUP
LEFT JOIN {{ ref('int_category_map') }} cm ON cm.RAW_CATEGORY = COALESCE(p.MATERIAL_GROUP, p.ITEM_TEXT) AND mg.MATERIAL_GROUP IS NULL
LEFT JOIN mg mg2 ON mg2.MATERIAL_GROUP = cm.MATERIAL_GROUP
LEFT JOIN org o ON o.PLANT = p.PLANT
LEFT JOIN {{ ref('int_supplier_xref') }} x ON x.SOURCE_SLOT = p.SOURCE_SLOT AND x.SUPPLIER_ID = p.SUPPLIER_ID
LEFT JOIN {{ ref('dim_supplier') }} s ON s.GOLDEN_SUPPLIER_ID = x.GOLDEN_SUPPLIER_ID
