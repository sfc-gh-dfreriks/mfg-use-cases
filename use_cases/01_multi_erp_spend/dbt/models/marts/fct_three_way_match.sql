-- PO line vs goods receipt vs invoice. Sources with no goods-receipt object (SAP BDC, Coupa)
-- show HAS_GR_DATA = FALSE rather than false exceptions.
WITH gr AS (SELECT SOURCE_SLOT, PO_NUMBER, PO_ITEM, SUM(GR_QTY) AS GR_QTY, MAX(GR_DATE) AS GR_DATE FROM {{ ref('goods_receipt') }} GROUP BY 1, 2, 3),
iv AS (SELECT SOURCE_SLOT, PO_NUMBER, PO_ITEM, SUM(INV_QTY) AS INV_QTY, SUM(INV_AMOUNT) AS INV_AMOUNT, MAX(INVOICE_DATE) AS INVOICE_DATE
       FROM {{ ref('invoice_line') }} WHERE PO_ITEM IS NOT NULL GROUP BY 1, 2, 3),
-- Coupa invoices reference the PO header, not a line: allocate them to lines by line value
iv_hdr AS (SELECT SOURCE_SLOT, PO_NUMBER, SUM(INV_AMOUNT) AS INV_AMOUNT, MAX(INVOICE_DATE) AS INVOICE_DATE
           FROM {{ ref('invoice_line') }} WHERE PO_ITEM IS NULL GROUP BY 1, 2),
po_tot AS (SELECT SOURCE_SLOT, PO_NUMBER, SUM(SPEND_LOCAL) AS PO_VALUE FROM {{ ref('fct_spend') }} GROUP BY 1, 2),
gr_slots AS (SELECT DISTINCT SOURCE_SLOT FROM {{ ref('goods_receipt') }})
SELECT s.SOURCE_SLOT, s.SOURCE_SYSTEM, s.COMPANY_NAME, s.PLANT_NAME, s.PO_NUMBER, s.PO_ITEM, s.PO_DATE, s.GOLDEN_SUPPLIER_ID, s.GOLDEN_SUPPLIER_NAME,
       s.CATEGORY, s.QUANTITY AS PO_QTY, s.NET_PRICE_LOCAL, s.SPEND_USD, s.CURRENCY,
       g.GR_QTY, g.GR_DATE, i.INV_QTY,
       COALESCE(i.INV_AMOUNT, h.INV_AMOUNT * s.SPEND_LOCAL / NULLIF(pt.PO_VALUE, 0)) AS INV_AMOUNT,
       COALESCE(i.INVOICE_DATE, h.INVOICE_DATE) AS INVOICE_DATE,
       (i.INV_AMOUNT IS NULL AND h.INV_AMOUNT IS NOT NULL) AS HEADER_LEVEL_INVOICE,
       (gs.SOURCE_SLOT IS NOT NULL) AS HAS_GR_DATA,
       DATEDIFF(day, s.DELIVERY_DATE, g.GR_DATE) AS DELIVERY_DELAY_DAYS,
       i.INV_AMOUNT / NULLIF(i.INV_QTY * s.NET_PRICE_LOCAL, 0) - 1 AS INVOICE_PRICE_VARIANCE_PCT,
       CASE
         WHEN i.INV_AMOUNT IS NULL AND h.INV_AMOUNT IS NOT NULL THEN 'Two-way only (header invoice)'
         WHEN i.INV_AMOUNT IS NULL THEN 'Not invoiced'
         WHEN gs.SOURCE_SLOT IS NULL THEN 'Two-way only (no GR data)'
         WHEN g.GR_QTY IS NULL THEN 'Invoice without receipt'
         WHEN i.INV_QTY > g.GR_QTY * 1.001 THEN 'Invoiced qty > received'
         WHEN ABS(i.INV_AMOUNT / NULLIF(i.INV_QTY * s.NET_PRICE_LOCAL, 0) - 1) > 0.01 THEN 'Price variance'
         ELSE 'Matched' END AS MATCH_STATUS
FROM {{ ref('fct_spend') }} s
LEFT JOIN gr g ON g.SOURCE_SLOT = s.SOURCE_SLOT AND g.PO_NUMBER = s.PO_NUMBER AND g.PO_ITEM = s.PO_ITEM
LEFT JOIN iv i ON i.SOURCE_SLOT = s.SOURCE_SLOT AND i.PO_NUMBER = s.PO_NUMBER AND i.PO_ITEM = s.PO_ITEM
LEFT JOIN iv_hdr h ON h.SOURCE_SLOT = s.SOURCE_SLOT AND h.PO_NUMBER = s.PO_NUMBER
LEFT JOIN po_tot pt ON pt.SOURCE_SLOT = s.SOURCE_SLOT AND pt.PO_NUMBER = s.PO_NUMBER
LEFT JOIN gr_slots gs ON gs.SOURCE_SLOT = s.SOURCE_SLOT
