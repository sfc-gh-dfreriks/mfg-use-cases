"""Scaffold a new use case that follows the framework.

    python3 framework/tools/new_use_case.py 03 connected_asset_health "Connected Asset Health / OEE" MFG_ASSET_HEALTH

Creates use_cases/<NN>_<slug>/ with the folder contract from framework/docs/FRAMEWORK.md: a dbt project with
`snowflake` and `local` targets and the shared macros, a data generator stub, a bronze loader, the config SQL, and
a README. The app is not scaffolded: copy use_cases/01_multi_erp_spend/app and replace its pages.
"""
import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
FRAMEWORK = ROOT / "framework"


def main(num: str, slug: str, title: str, database: str) -> None:
    if not re.fullmatch(r"\d{2}", num) or not re.fullmatch(r"[a-z][a-z0-9_]*", slug) or not re.fullmatch(r"[A-Z][A-Z0-9_]*", database):
        sys.exit("usage: new_use_case.py <NN> <slug_lowercase> <title> <DATABASE_UPPERCASE>")
    d = ROOT / "use_cases" / f"{num}_{slug}"
    if d.exists():
        sys.exit(f"{d} already exists")
    project = f"mfg_{slug}"
    for sub in ["data_gen", "tools", "sql", "docs", "dbt/models/staging", "dbt/models/intermediate", "dbt/models/marts", "dbt/macros", "dbt/tests"]:
        (d / sub).mkdir(parents=True)
    for m in (FRAMEWORK / "dbt_macros").glob("*.sql"):
        shutil.copy(m, d / "dbt/macros" / m.name)
    (d / "dbt/dbt_project.yml").write_text(f"""name: {project}
version: "1.0.0"
config-version: 2
profile: {project}

model-paths: ["models"]
macro-paths: ["macros"]
test-paths: ["tests"]

vars:
  # Source selection: passed with --vars by the app, else read from CONFIG.SOURCE_SELECTION.
  selection: null

models:
  {project}:
    staging:
      +schema: ADAPTERS
      +materialized: view
    intermediate:
      +schema: SILVER
      +materialized: view
    marts:
      +schema: GOLD
      +materialized: dynamic_table
      +target_lag: "1 day"
      +snowflake_warehouse: COMPUTE_WH
""")
    (d / "dbt/profiles.yml").write_text(f"""# snowflake (default): runs inside Snowflake as a dbt project object; no credentials.
# local: dbt CLI with key-pair auth; select with DBT_TARGET=local.
{project}:
  target: "{{{{ env_var('DBT_TARGET', 'snowflake') }}}}"
  outputs:
    snowflake:
      type: snowflake
      account: ""
      user: ""
      role: ACCOUNTADMIN
      warehouse: COMPUTE_WH
      database: {database}
      schema: SILVER
      threads: 8
    local:
      type: snowflake
      account: "{{{{ env_var('SNOWFLAKE_ACCOUNT') }}}}"
      user: "{{{{ env_var('SNOWFLAKE_USER') }}}}"
      authenticator: snowflake_jwt
      private_key_path: "{{{{ env_var('SNOWFLAKE_PRIVATE_KEY_PATH') }}}}"
      role: ACCOUNTADMIN
      warehouse: COMPUTE_WH
      database: {database}
      schema: SILVER
      threads: 8
""")
    (d / "dbt/macros/canonical_columns.sql").write_text("""-- The canonical column contract every adapter maps into. Fill in one entry per canonical object.
{% macro canonical_columns(object_name) %}
  {%- set cols = {
    'EXAMPLE_OBJECT': [('SOURCE_SLOT','STRING'), ('SOURCE_SYSTEM','STRING')],
  } -%}
  {{ return(cols[object_name]) }}
{% endmacro %}
""")
    (d / "dbt/macros/adapter_registry.sql").write_text("""-- Generated by tools/build_silver_sql.py: object -> slot -> system -> staging model
{% macro adapter_registry() %}
  {{ return({}) }}
{% endmacro %}
""")
    (d / "data_gen/generate.py").write_text(f'''"""Synthetic data for {title}.

Generate business events once, then render them into each source system's native tables
(data_gen/out/<SCHEMA>/<TABLE>.parquet) so totals reconcile whichever source type is selected.
"""
''')
    shutil.copy(ROOT / "use_cases/01_multi_erp_spend/data_gen/load_bronze.py", d / "data_gen/load_bronze.py")
    lb = d / "data_gen/load_bronze.py"
    lb.write_text(lb.read_text().replace('DB = "MFG_SPEND_RISK"', f'DB = "{database}"').replace("Multi-ERP Spend & Supplier Risk", title))
    (d / "sql/03_config.sql").write_text(f"""-- Source selection written by the app's Data Sources screen and read by dbt when no --vars are passed.
USE DATABASE {database};
CREATE SCHEMA IF NOT EXISTS CONFIG;
CREATE TABLE IF NOT EXISTS CONFIG.SOURCE_SELECTION (SOURCE_SLOT STRING, SYSTEM_CODE STRING, ENABLED BOOLEAN,
  UPDATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(), UPDATED_BY STRING DEFAULT CURRENT_USER());
CREATE TABLE IF NOT EXISTS CONFIG.SOURCE_SLOT (SOURCE_SLOT STRING, LABEL STRING, KIND STRING, SCOPE STRING, ALLOWED_SYSTEMS ARRAY, SORT_ORDER INT);
CREATE TABLE IF NOT EXISTS CONFIG.REBUILD_LOG (RUN_ID STRING, STARTED_AT TIMESTAMP_LTZ, FINISHED_AT TIMESTAMP_LTZ, STATUS STRING,
  SELECTION VARIANT, MESSAGE STRING);
""")
    (d / "README.md").write_text(f"""# {title}

Use case {num} of the SAP Manufacturing Use Case Playbook, built on the portable framework
([framework/docs/FRAMEWORK.md](../../framework/docs/FRAMEWORK.md)). Database `{database}`.

## Status

Scaffolded. Next: define the canonical objects from the playbook gap analysis, write `data_gen/generate.py`
and `tools/build_silver_sql.py`, then the silver and gold models, semantic view, agent and app.
""")
    print(f"created {d.relative_to(ROOT)}")


if __name__ == "__main__":
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    main(*sys.argv[1:])
